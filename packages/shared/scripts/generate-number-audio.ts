/**
 * Records the number chart's spoken words (1 to 100) as MP3 files with Azure
 * Speech, for languages most devices have no built-in voice for (Burmese) or
 * only a poor one (Thai). Output goes to apps/web/public/audio/numbers/<locale>/<n>.mp3
 * and the list of recorded numbers to apps/web/src/lib/number-audio.ts.
 *
 * Existing files are kept, so hand-made recordings dropped into the same folders
 * (same names) win; pass --force to re-record everything.
 *
 *   pnpm audio:numbers   # reads AZURE_SPEECH_KEY / AZURE_SPEECH_REGION from apps/web/.env.local
 *   pnpm audio:numbers -- --locales my,th,en --force
 *   pnpm audio:numbers -- --manifest-only   # just rescan the folders
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LOCALES, LOCALE_TAGS, type Locale } from '../src/i18n/locales';
import { numberToWords } from '../src/math/words';

const MAX = 100;

// Neural voices that read number words clearly at a child-friendly pace.
const VOICES: Record<Locale, string> = {
  en: 'en-US-AnaNeural',
  my: 'my-MM-NilarNeural',
  th: 'th-TH-PremwadeeNeural',
};

const here = dirname(fileURLToPath(import.meta.url));
const audioDir = resolve(here, '../../../apps/web/public/audio/numbers');
const manifestFile = resolve(here, '../../../apps/web/src/lib/number-audio.ts');

const args = process.argv.slice(2);
const flag = (name: string) => args.includes(`--${name}`);
const option = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};

const locales = (option('locales') ?? 'my,th').split(',').map((l) => l.trim()) as Locale[];
for (const l of locales) if (!LOCALES.includes(l)) throw new Error(`Unknown locale "${l}". Use any of: ${LOCALES.join(', ')}`);

const fileFor = (locale: Locale, n: number) => resolve(audioDir, locale, `${n}.mp3`);
const escapeXml = (s: string) => s.replace(/[<>&'"]/g, (c) => `&#${c.charCodeAt(0)};`);
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function synthesize(locale: Locale, text: string, key: string, region: string): Promise<Buffer> {
  const lang = locale === 'en' ? 'en-US' : LOCALE_TAGS[locale];
  const ssml = `<speak version="1.0" xml:lang="${lang}"><voice name="${VOICES[locale]}"><prosody rate="-15%">${escapeXml(text)}</prosody></voice></speak>`;
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(`https://${region}.tts.speech.microsoft.com/cognitiveservices/v1`, {
      method: 'POST',
      headers: {
        'Ocp-Apim-Subscription-Key': key,
        'Content-Type': 'application/ssml+xml',
        'X-Microsoft-OutputFormat': 'audio-24khz-48kbitrate-mono-mp3',
        'User-Agent': 'math-adventure-number-audio',
      },
      body: ssml,
    });
    if (res.ok) return Buffer.from(await res.arrayBuffer());
    // The free tier allows about 20 requests a minute; wait and retry when throttled.
    if ((res.status === 429 || res.status >= 500) && attempt < 6) {
      const wait = Number(res.headers.get('retry-after')) * 1000 || 3000 * attempt;
      await sleep(wait);
      continue;
    }
    throw new Error(`Azure Speech ${res.status} for ${locale} "${text}": ${await res.text()}`);
  }
}

async function record() {
  // Pick up AZURE_SPEECH_KEY / AZURE_SPEECH_REGION from the web app's git-ignored env file.
  const envFile = resolve(here, '../../../apps/web/.env.local');
  if (existsSync(envFile)) process.loadEnvFile(envFile);
  const key = process.env.AZURE_SPEECH_KEY;
  const region = process.env.AZURE_SPEECH_REGION;
  if (!key || !region) {
    console.error('Set AZURE_SPEECH_KEY and AZURE_SPEECH_REGION (e.g. southeastasia). See the comment at the top of this script.');
    process.exit(1);
  }
  for (const locale of locales) {
    mkdirSync(resolve(audioDir, locale), { recursive: true });
    let made = 0;
    for (let n = 1; n <= MAX; n++) {
      const file = fileFor(locale, n);
      if (existsSync(file) && !flag('force')) continue;
      writeFileSync(file, await synthesize(locale, numberToWords(n, locale), key, region));
      made++;
      process.stdout.write(`\r${locale}: ${n}/${MAX}`);
    }
    console.log(`\r${locale}: recorded ${made}, kept ${MAX - made}`);
  }
}

/** Counts how far each language is recorded without gaps, so the chart only plays files that exist. */
function writeManifest() {
  const recorded: Partial<Record<Locale, number>> = {};
  for (const locale of LOCALES) {
    let n = 0;
    while (n < MAX && existsSync(fileFor(locale, n + 1))) n++;
    if (n) recorded[locale] = n;
  }
  writeFileSync(
    manifestFile,
    `// GENERATED by packages/shared/scripts/generate-number-audio.ts — do not edit by hand.
import type { Locale } from '@math-adventure/shared';

/** For each language, numbers 1 to this value have a recording in /audio/numbers/<locale>/<n>.mp3. */
export const NUMBER_AUDIO_UP_TO: Partial<Record<Locale, number>> = ${JSON.stringify(recorded)};

export function numberAudioUrl(locale: Locale, n: number): string | null {
  return n >= 1 && n <= (NUMBER_AUDIO_UP_TO[locale] ?? 0) ? \`/audio/numbers/\${locale}/\${n}.mp3\` : null;
}
`,
  );
  console.log('Recorded ranges:', recorded);
}

if (!flag('manifest-only')) await record();
writeManifest();
